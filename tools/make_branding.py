#!/usr/bin/env python3
"""Turn the AeroRelics artwork in branding/ into what the firmware and the installer use.

    branding/MFD_splash.jpg          -> src/splash_img.cpp  (800x480 RGB565, boot splash)
    branding/logo_banner.webp        -> app banner (PNG) and the icon (.ico) for the app and setup
    branding/installer_welcome.webp  -> setup's welcome page and side images (BMP)

    python tools/make_branding.py            # splash source only (commit the result)
    make_release.py calls build_app_assets() for the app and installer images.

The panel's pixels are 7.7 % wider than tall, so the splash is squeezed horizontally by XS
before it is cropped to 800 x 480; it then looks like the original on the glass.
"Version 2.5" in the artwork is painted out: the firmware draws its own version there.
"""
import os

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BRAND = os.path.join(ROOT, "branding")
XS = 0.9286                     # src/ui_priv.h
W, H = 800, 480
NAVY = (34, 59, 87)             # bottom of the installer artwork
VERSION_END = 371               # splash: right edge of "Version 2.5" (the "|" follows at 377)


def splash_image():
    """800 x 480 RGB of the splash as it should be drawn, its version number painted out."""
    src = Image.open(os.path.join(BRAND, "MFD_splash.jpg")).convert("RGB")
    sw, sh = src.size
    scaled_w = round(sw * H / sh * XS)
    im = src.resize((scaled_w, H), Image.LANCZOS)
    x0 = (scaled_w - W) // 2
    im = im.crop((x0, 0, x0 + W, H))
    a = np.asarray(im).copy()
    # "Version 2.5 | (c) 2024 AeroRelics" (y ~ 625 of 720 in the artwork): paint out
    # "Version 2.5" (x < VERSION_END + 4 here) with the background from just above it; the
    # firmware draws its own version there, right-aligned to VERSION_END. The rest stays.
    y_text = round(625 * H / sh)
    a[y_text - 14:y_text + 14, 280:VERSION_END + 4] = a[y_text - 44:y_text - 16, 280:VERSION_END + 4]
    return Image.fromarray(a), y_text


def write_splash_source():
    im, y_text = splash_image()
    a = np.asarray(im).astype(np.uint16)
    rgb565 = ((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)
    words = rgb565.ravel()
    out = os.path.join(ROOT, "src", "splash_img.cpp")
    with open(out, "w", newline="\n") as f:
        f.write("// Boot splash, 800x480 RGB565. Generated by tools/make_branding.py from\n"
                "// branding/MFD_splash.jpg - do not edit.\n#include <stdint.h>\n\n")
        f.write(f"extern const int SPLASH_VERSION_Y = {y_text};      // centre of the version text\n")
        f.write(f"extern const int SPLASH_VERSION_END = {VERSION_END};   // its right edge\n")
        f.write("extern const uint16_t SPLASH_IMG[800 * 480] = {\n")
        for i in range(0, words.size, 16):
            f.write(",".join(f"0x{w:04X}" for w in words[i:i + 16].tolist()) + ",\n")
        f.write("};\n")
    preview = os.path.join(ROOT, "tools", "ui_preview", "out")
    os.makedirs(preview, exist_ok=True)
    im.save(os.path.join(preview, "splash_converted.png"))
    print(f"wrote {out} ({os.path.getsize(out) // 1024} KB source), version line at y={y_text}")


def logo_circle(size):
    """The red roundel from the banner, as a square RGBA image with transparent corners."""
    im = Image.open(os.path.join(BRAND, "logo_banner.webp")).convert("RGBA")
    a = np.asarray(im)
    red = (a[..., 0] > 140) & (a[..., 1] < 90) & (a[..., 2] < 90) & (a[..., 3] > 200)
    cols = np.nonzero(red[:, :400].any(axis=0))[0]
    rows = np.nonzero(red[:, :400].any(axis=1))[0]
    box = (cols.min(), rows.min(), cols.max() + 1, rows.max() + 1)
    disc = im.crop(box)
    d = max(disc.size)
    sq = Image.new("RGBA", (d, d), (0, 0, 0, 0))
    sq.paste(disc, ((d - disc.size[0]) // 2, (d - disc.size[1]) // 2))
    mask = Image.new("L", (d * 4, d * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, d * 4 - 1, d * 4 - 1), fill=255)
    sq.putalpha(Image.fromarray(np.minimum(np.asarray(sq)[..., 3], np.asarray(mask.resize((d, d), Image.LANCZOS)))))
    return sq.resize((size, size), Image.LANCZOS)


def build_app_assets(out_dir):
    """Icon, app banner and installer bitmaps into out_dir; returns their paths."""
    os.makedirs(out_dir, exist_ok=True)
    paths = {}
    icon = logo_circle(256)
    paths["ico"] = os.path.join(out_dir, "mfd.ico")
    icon.save(paths["ico"], sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])

    banner = Image.open(os.path.join(BRAND, "logo_banner.webp")).convert("RGBA")
    bw = 560
    banner = banner.resize((bw, round(banner.size[1] * bw / banner.size[0])), Image.LANCZOS)
    paths["banner"] = os.path.join(out_dir, "banner.png")
    banner.save(paths["banner"])

    # Setup: full-page welcome image at several DPI scales, on navy (its corners are transparent).
    welcome = Image.open(os.path.join(BRAND, "installer_welcome.webp")).convert("RGBA")
    flat = Image.new("RGB", welcome.size, NAVY)
    flat.paste(welcome, (0, 0), welcome)
    paths["welcome"] = []
    for h in (314, 392, 471, 628):
        p = os.path.join(out_dir, f"welcome_{h}.bmp")
        flat.resize((round(flat.size[0] * h / flat.size[1]), h), Image.LANCZOS).save(p)
        paths["welcome"].append(p)
    # Side image of the last page (164 x 314 at 100 %) and the small top-right logo (55 x 55).
    paths["side"], paths["small"] = [], []
    for scale in (1.0, 1.25, 1.5, 2.0):
        w, h = round(164 * scale), round(314 * scale)
        side = Image.new("RGB", (w, h), NAVY)
        top = Image.new("RGB", (w, h), (12, 24, 36))
        grad = Image.linear_gradient("L").resize((w, h))
        side = Image.composite(side, top, grad)
        disc = logo_circle(round(w * 0.78))
        side.paste(disc, ((w - disc.size[0]) // 2, round(h * 0.18)), disc)
        p = os.path.join(out_dir, f"side_{int(scale * 100)}.bmp")
        side.save(p)
        paths["side"].append(p)
        s = round(55 * scale)
        small = Image.new("RGB", (s, s), (255, 255, 255))
        disc = logo_circle(s)
        small.paste(disc, (0, 0), disc)
        p = os.path.join(out_dir, f"small_{int(scale * 100)}.bmp")
        small.save(p)
        paths["small"].append(p)
    return paths


if __name__ == "__main__":
    write_splash_source()
